import {test} from "node:test";
import assert from "node:assert/strict";
import {validate,branchErrors,cmp} from "../qa/check-application-governance.mjs";
const c={apps:{"consubov-fazendas-app":"2.0.0","admin-global-app":null,"mais-arrobas-app":null,"syncvet-app":null,"relatto-app":null},sites:["consubov-site","relatto-site"]};
test("baseline 2.0.0 valid",()=>assert.deepEqual(validate(c),[]));
test("regression 1.155.0 rejected",()=>assert.match(validate({...c,apps:{...c.apps,"consubov-fazendas-app":"1.155.0"}}).join(","),/regression/));
test("sites never versioned",()=>assert.match(validate({...c,sites:[{id:"consubov-site",version:"1.0.0"}]}).join(","),/sites may not have version/));
test("no global version",()=>assert.match(validate({...c,version:"3.0.0"}).join(","),/global version/));
test("new apps unversioned",()=>assert.deepEqual(validate({...c,apps:{...c.apps,"future-app":null}}),[]));
test("separate releases",()=>assert.deepEqual(validate({...c,apps:{...c.apps,"syncvet-app":"1.0.0"}}),[]));
test("tags prevent regressions",()=>assert.match(validate(c,["consubov-fazendas-app/v2.1.0"]).join(","),/regression/));
test("release must increment",()=>assert.match(validate(c,[],"consubov-fazendas-app").join(","),/increment/));
test("invalid SemVer",()=>assert.match(validate({...c,apps:{...c.apps,"syncvet-app":"v1.0.0"}}).join(","),/invalid app version/));
test("numeric SemVer compare",()=>assert.equal(cmp("2.10.0","2.9.9"),1));
test("valid branch",()=>assert.deepEqual(branchErrors("fix/platform/gov-001-proteger-versoes-ramos",c),[]));
test("invalid branch",()=>assert.ok(branchErrors("fix/site-old-20261029",c).length));
test("existing branch accepted",()=>assert.deepEqual(branchErrors("fix/site-old-20261029",c,["fix/site-old-20261029"]),[]));
test("bots accepted",()=>assert.deepEqual(branchErrors("dependabot/bun/react-19",c),[]));
test("unknown scope blocked",()=>assert.match(branchErrors("fix/invented-app/gov-001-fix",c).join(","),/unknown/));
test("hotfix must be incident",()=>assert.match(branchErrors("hotfix/platform/gov-001-fix",c).join(","),/incident/));
