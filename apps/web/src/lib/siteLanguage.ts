export function siteCopy(
  language: SiteLanguage,
  key: string,
  fallback: string,
  fromCms: (key: string, fallback: string) => string,
): string {
  if (language === "en-US" && Object.prototype.hasOwnProperty.call(SITE_EN, key)) {
    return SITE_EN[key];
  }
  return fromCms(key, fallback);
}

export function sitePhrase(language: SiteLanguage, text: string): string {
  return language === "en-US" ? (SITE_PHRASES_EN[text] ?? text) : text;
}
